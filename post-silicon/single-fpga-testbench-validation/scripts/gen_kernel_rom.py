#!/usr/bin/env python3
"""Generate rtl/kernel_rom.v from the 5x5 testcases.

Each entry holds a testcase's 25 kernel bytes (row-major, kernel.hex order),
its NORMALIZATION_VALUE and TEST_MODE from config.yml. The buttons on the
board step through the entries in live mode.

Usage: gen_kernel_rom.py <testcases/5x5 dir> <out kernel_rom.v>
"""
import pathlib
import re
import sys


def main(case_dir, out):
    cases = sorted(p for p in pathlib.Path(case_dir).iterdir() if (p / "config.yml").exists())
    entries = []
    for p in cases:
        kernel = [int(t, 16) & 0xFF for t in (p / "kernel.hex").read_text().split()]
        assert len(kernel) == 25, p
        cfg = (p / "config.yml").read_text()
        norm = int(re.search(r"NORMALIZATION_VALUE=(\d+)", cfg).group(1))
        test_mode = 1 if re.search(r"TEST_MODE=1", cfg) else 0
        entries.append((p.name, kernel, norm, test_mode))

    lines = [
        "// Generated by scripts/gen_kernel_rom.py from testcases/5x5; do not edit.",
        "// Entry: 25 kernel bytes (byte k at kernel[8k +: 8]), 16-bit norm, test_mode.",
        "module kernel_rom (",
        "    input  wire [3:0]   index,",
        "    output reg  [199:0] kernel,",
        "    output reg  [15:0]  norm,",
        "    output reg          test_mode",
        ");",
        "",
        f"    localparam ENTRIES = {len(entries)};",
        "",
        "    always @(*) begin",
        "        case (index)",
    ]
    for i, (name, kernel, norm, tm) in enumerate(entries):
        word = "".join(f"{b:02x}" for b in reversed(kernel))
        lines.append(f"            4'd{i}: begin kernel = 200'h{word}; norm = 16'd{norm}; test_mode = 1'b{tm}; end  // {name}")
    lines += [
        "            default: begin kernel = 200'd0; norm = 16'h8000; test_mode = 1'b0; end",
        "        endcase",
        "    end",
        "",
        "endmodule",
        "",
    ]
    pathlib.Path(out).write_text("\n".join(lines))
    for i, (name, *_rest) in enumerate(entries):
        print(f"{i}: {name}")


if __name__ == "__main__":
    main(*sys.argv[1:])
