#!/usr/bin/env python3
"""Turn a camera register list into a ROM for the FPGA's SCCB init engine.

Usage: gen_cam_rom.py <regs.txt> <out.v> [--expected out.hex]

Register list format (same file cam_host.py init uses):
  <addr> <data>     hex, one 16-bit-address register write
  delay <ms>        wait
  # ...             comment

ROM entries are 32 bits:
  [31:30] op: 0 write, 1 delay, 3 end
  [23:8]  register address (write)   [7:0] data (write)
  [23:0]  milliseconds (delay)
--expected writes one "AAAADD" hex word per register write, in order, for
the testbench's SCCB monitor.
"""
import argparse
import sys


def parse(path):
    ops = []
    for n, raw in enumerate(open(path), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        a, b = line.split()
        if a == "delay":
            ms = int(b)
            if not 0 < ms < 1 << 24:
                sys.exit(f"{path}:{n}: delay out of range")
            ops.append(("delay", ms))
        else:
            addr, data = int(a, 16), int(b, 16)
            if addr >> 16 or data >> 8:
                sys.exit(f"{path}:{n}: address or data out of range")
            ops.append(("write", addr, data))
    return ops


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("regs")
    ap.add_argument("out")
    ap.add_argument("--expected")
    a = ap.parse_args()

    ops = parse(a.regs)
    words = []
    for op in ops:
        if op[0] == "write":
            words.append((0 << 30) | (op[1] << 8) | op[2])
        else:
            words.append((1 << 30) | op[1])
    words.append(3 << 30)
    aw = 10                                  # fixed interface: 10-bit address
    depth = 512
    if len(words) > depth:
        sys.exit(f"{a.regs}: {len(words)} entries, the ROM holds {depth}")
    words += [3 << 30] * (depth - len(words))   # the rest: end

    v = [
        f"// Generated by scripts/gen_cam_rom.py from {a.regs.split('/')[-1]}; do not edit.",
        f"// {sum(o[0] == 'write' for o in ops)} register writes, "
        f"{sum(o[0] == 'delay' for o in ops)} delays.",
        "module cam_init_rom (",
        "    input  wire        clk,",
        f"    input  wire [{aw - 1}:0] addr,",
        "    output reg  [31:0] data          // 1-cycle read latency",
        ");",
        "",
        "    // logic (LUTs): in block RAM the address path from sccb_init's index",
        "    // register is short enough to fail nextpnr's hold check",
        "    (* ram_style = \"logic\" *)",
        f"    reg [31:0] rom [0:{depth - 1}];",
        "    initial begin",
    ]
    for i, w in enumerate(words):
        v.append(f"        rom[{i}] = 32'h{w:08x};")
    v += [
        "    end",
        "",
        "    always @(posedge clk)",
        # sccb_init stops at the first end entry, which is always below 512
        f"        data <= rom[addr[{(depth - 1).bit_length() - 1}:0]];",
        "",
        "endmodule",
        "",
    ]
    open(a.out, "w").write("\n".join(v))

    if a.expected:
        with open(a.expected, "w") as f:
            for op in ops:
                if op[0] == "write":
                    f.write(f"{op[1]:04x}{op[2]:02x}\n")


if __name__ == "__main__":
    main()
